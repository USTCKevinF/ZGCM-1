def language_for_path(path: str) -> str | None:
    """Return the normalized language label used by the GHArchive cleaner."""
    name = PurePosixPath(path.replace("\\", "/")).name.casefold()
    if name in SPECIAL_NAMES:
        return SPECIAL_NAMES[name]
    return LANGUAGE_BY_EXTENSION.get(PurePosixPath(name).suffix.casefold())


def reject_path_reason(path: str, size_bytes: int = 0, *, max_file_bytes: int = 0) -> str | None:
    """Classify explicit non-source paths without using machine-specific state."""
    normalized = "/" + path.replace("\\", "/").casefold().lstrip("/")
    pure = PurePosixPath(normalized)
    name = pure.name
    extension = pure.suffix
    parts = {part.casefold() for part in pure.parts}
    if name.endswith((".min.js", ".min.css", ".min.html")):
        return "minified_asset"
    if parts.intersection(REJECT_DIRS):
        return "vendor_or_build_path"
    if name in LOCK_FILES:
        return "lockfile"
    if extension in BINARY_EXTENSIONS:
        return "binary_extension"
    if any(marker in normalized for marker in SNAPSHOT_MARKERS):
        return "fixture_or_snapshot"
    if any(marker in normalized for marker in ("/html-report/", "/reports/", "/test-output/")):
        return "machine_report"
    if max_file_bytes > 0 and int(size_bytes) > max_file_bytes:
        return "configured_size_limit"
    if language_for_path(path) is None:
        return "unsupported_file_type"
    return None


def normalize_notebook(text: str) -> str:
    """Keep notebook source cells and discard execution outputs and metadata."""
    try:
        notebook = json.loads(text)
    except (TypeError, json.JSONDecodeError):
        return text
    chunks: list[str] = []
    for cell in notebook.get("cells", []):
        if not isinstance(cell, dict):
            continue
        source = cell.get("source", "")
        if isinstance(source, list):
            source = "".join(str(item) for item in source)
        if not isinstance(source, str) or not source.strip():
            continue
        marker = "<!-- markdown cell -->" if cell.get("cell_type") == "markdown" else "# code cell"
        chunks.append(f"{marker}\n{source.strip()}")
    return "\n\n".join(chunks).strip()


def is_minified(text: str) -> bool:
    if len(text) < 2_000:
        return False
    lines = text.splitlines()
    if not lines:
        return False
    longest = max(len(line) for line in lines)
    average = sum(len(line) for line in lines) / len(lines)
    return longest > 200_000 or (len(lines) < 10 and average > 1_000)


def clean_gharchive_record(sample: Sample, context: PipelineContext) -> Sample:
    """Normalize and filter one source-file record extracted from a release zip."""
    data = sample.data
    metadata = data.get("meta") if isinstance(data.get("meta"), dict) else data.get("metadata")
    metadata = dict(metadata) if isinstance(metadata, dict) else {}
    path = str(data.get("path") or data.get("file_path") or metadata.get("path") or "")
    text = data.get("text") if isinstance(data.get("text"), str) else data.get("content")
    if not isinstance(text, str):
        sample.mark(Decision.DROP, "gharchive_missing_text")
        return sample
    text = text.replace("\r\n", "\n").replace("\r", "\n").strip()
    if "\x00" in text[:8192]:
        sample.mark(Decision.DROP, "gharchive_binary_nul")
        return sample
    size_bytes = int(data.get("length_bytes") or metadata.get("length_bytes") or len(text.encode("utf-8")))
    reason = reject_path_reason(
        path,
        size_bytes,
        max_file_bytes=int(context.config.get("gharchive_max_file_bytes", 0)),
    )
    if reason:
        sample.mark(Decision.DROP, f"gharchive_{reason}")
        return sample
    language = language_for_path(path) or str(data.get("language") or metadata.get("language") or "unknown")
    if language == "Notebook":
        text = normalize_notebook(text)
    if not text:
        sample.mark(Decision.DROP, "gharchive_empty_text")
        return sample
    prefix = text[:2_000].casefold()
    if any(marker in prefix for marker in GENERATED_MARKERS):
        sample.mark(Decision.DROP, "gharchive_generated_file")
        return sample
    if is_minified(text):
        sample.mark(Decision.DROP, "gharchive_minified_or_long_line")
        return sample

    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    data["text"] = text
    data["path"] = path
    data["language"] = language
    data.setdefault("source", str(metadata.get("source") or "gharchive_release_zip"))
    metadata.setdefault("blob_id", f"sha256:{digest}")
    metadata.setdefault("path", path)
    metadata.setdefault("language", language)
    data["metadata"] = metadata
    sample.text_fields = ("text",)
    sample.buckets["language"] = language
    sample.buckets["gharchive_bucket"] = "core"
    return sample


